export const cheapestPackPrice = () => Math.min(...PACKS.map((p) => p.price));

/**
 * 한 봉에서 레전드가 **적어도 한 장** 나올 확률(%, 정수).
 *
 * 장당 확률(플래티넘 9%)을 그대로 적으면 실제 체감보다 훨씬 인색해 보인다. 여덟 장을
 * 한 번에 뜯으니 사람이 궁금한 건 "이 봉에서 레전드를 볼까"지 장당 확률이 아니다.
 */
export function legendChance(pack: Pack): number {
  return Math.round((1 - (1 - pack.rates.LEGEND / 100) ** pack.size) * 100);
}

/** 팩 하나를 열어 전부 팔았을 때 받을 금액의 기댓값. 엣지를 재는 데 쓴다. */
export function packExpectedValue(pack: Pack): number {
  const perCard = TIERS.reduce((s, t) => s + (pack.rates[t.key] / 100) * BASE_VALUE[t.key], 0);
  return perCard * pack.size;
}

/** 카드 가치 = 기본가 × 그 단계까지의 누적 배수. 판매가이자 이 게임의 성과 점수다. */
export function cardValue(tier: TierKey, plus: number): number {
  // 표에서 읽으므로 범위를 벗어나면 undefined 가 되어 NaN 이 번져나간다(예전 GROWTH ** plus
  // 는 어떤 값이 와도 숫자였다). 저장값 검증처럼 천장 밖 plus 를 물어보는 자리가 있어 자른다.
  return Math.round(BASE_VALUE[tier] * MULT[Math.min(Math.max(plus, 0), MAX_PLUS)]);
}

/**
 * 강화 세 구간 규칙. 나중에 숫자(STEP_GROWTH·ODDS·guardFee)를 만질 사람은 이걸
 * 먼저 읽어야 한다.
 *
 * - **+0~+5 위험 0 구간**: 파괴가 없다. 기대손익은 반드시 음수여야 한다. 여기가
 *   양수면 위험 없는 반복 클릭이 최적 플레이가 된다(예전에 실제로 그랬다).
 * - **+6~+10 도박 구간**: 파괴가 있고, 기대손익은 양수다. 카드 목숨을 걸어야
 *   나오는 이득이라 "강화장사"라 부른다.
 * - **+11~+14 트로피 구간**: 기대손익이 크게 음수다. 돈으로는 손해가 뻔한
 *   구간이고, 여기까지 미는 건 돈이 아니라 숫자(강화 표시) 자체를 보려는 것이다.
 *
 * "전 구간 기대손익 음수"는 파괴가 애초에 없을 때나 성립하는 규칙이다. 파괴가
 * +6부터 있는 지금은 그 위 구간이 이미 도박이라, 기대손익이 양수여도 무위험
 * 노동이 되지 않는다. 직전 개편(B안)은 이 구분 없이 전 구간을 음수로 묶어 도박
 * 구간의 강화장사를 원리적으로 막아버렸다 — 그래서 재조율했다.
 */

/**
 * 강화 한 번 시도의 [성공, 파괴] 확률(%). 나머지가 실패(단계 유지)다.
 *
 * **파괴는 +6부터** 시작한다. 누적배수가 2배를 넘는 지점과 맞춰, 그 앞은 돈만 잃고
 * 카드는 안 사라지는 안전 구간, +6부터는 카드 목숨을 거는 구간으로 가른다.
 *
 * 도박 구간(+6~+10)의 파괴율을 이전(4/7/11/16/22)에서 6/9/10/11/11로 낮췄다.
 * 파괴 22%를 성공 배수로 갚으려면 배수가 1.95까지 필요했고, 그 큰 배수가 복리로
 * 굴러 레전드 +15를 9만대로 밀어올렸다(위 STEP_GROWTH 참고). 파괴를 낮추면 같은
 * 본전을 훨씬 작은 배수로 만들 수 있다. 한 번에 거는 돈이 전 재산과 맞먹어 판이
 * 중앙값 4~6팩에 끝나던 것도 이 파괴율 탓이었다.
 *
 * 트로피 구간(+11~+14)은 반대로 29/36/43/50에서 35/42/48/55로 올렸다. 도박
 * 구간에서 줄인 만큼 여기서 마저 걷어야 "미친 짓" 느낌이 유지된다.
 */
const ODDS: readonly (readonly [number, number])[] = [
  [98, 0],
  [95, 0],
  [90, 0],
  [84, 0],
  [76, 0],
  [66, 0],
  [55, 6],
  [47, 9],
  [40, 10],
  [34, 11],
  [28, 11],
  [22, 35],
  [17, 42],
  [12, 48],
  [8, 55],
];

export type Odds = { success: number; keep: number; destroy: number };

/** guard 를 켜면 파괴 확률이 실패로 흡수된다. 성공률은 그대로다. */
export function oddsAt(plus: number, guard: boolean): Odds {
  const row = ODDS[plus];
  if (!row) return { success: 0, keep: 100, destroy: 0 };
  const [success, destroy] = row;
  const keep = 100 - success - destroy;
  return guard ? { success, keep: keep + destroy, destroy: 0 } : { success, keep, destroy };
}

/**
 * 강화비. 구간마다 다른 규칙을 쓴다(2026-08 재조율, 주인이 여러 판 해보고 온 피드백).
 *
 * - **+0~+5 안전 구간**: `ceil(카드 가치 × 11%)`. "+0~+5를 올려서 되판다"는
 *   차익을 없애는 벽이다.
 * - **+6~+14 도박·트로피 구간**: `ceil(기본가 × 12%)`. 가치에 비례하지 않고 등급별
 *   고정값이다.
 *
 * 예전엔 `min(가치×11%, 기본가×20%)` 하나로 뭉뚱그렸다. +0~+5 에서는 가치×11%가
 * 항상 기본가×20%보다 작아(MULT[5]=1.6248 이라 가치×11% = 기본가×17.9%) min 이 거기서
 * 걸린 적이 없었으니, 구간을 나눠 써도 안전 구간 값은 하나도 안 바뀐다.
 *
 * 바뀐 건 상한 그 자체다: 20% → 12%. 피드백은 "망했을 때 복구할 희망이 살짝만 더
 * 있으면 좋겠다. 언커먼~레어를 강화해서 팔 때, 강화를 해봤자 더 손해다. 어차피 7카
 * 8카는 가야 본전이라서다" 였다. 재보니 사실이었다 — 상한이 20%일 때 손익분기가
 * (등급 무관) +9였다. 상한을 12%로 낮추면 도박 구간(+6~) 강화비가 등급 기본가의
 * 20%에서 12%로 내려가 손익분기가 +7(레어·에픽·레전드)/+8(커먼·언커먼)로 당겨진다.
 * 예: 레어 강화비 50→30, 에픽 140→84, 레전드 400→240.
 *
 * 안전 구간(11%)은 안 낮춘다. 10%로 내려 봤더니 커먼 +3(가치 39)에서 강화비가
 * 5→4로 줄어 기대손익이 반올림 오차로 양수가 됐다(다음 단계 가치 44, 성공률 84% →
 * 0.84×5−4 = +0.2). 안전 구간은 "위험 없는 반복 클릭이 이득이면 안 된다"는 규칙이
 * 정수 반올림 오차로도 뒤집히면 안 되는 자리라 11%를 유지한다.
 *
 * `round` 가 아니라 `ceil` 을 쓰는 이유도 같다 — 반올림은 위 커먼 사례처럼 정수
 * 기대손익을 양수 쪽으로 밀어붙인다. 연속값이 아니라 실제로 지불하는 정수에서
 * "안전 구간은 항상 음수"가 지켜져야 한다.
 */
export function upgradeCost(tier: TierKey, plus: number): number {
  return plus <= 5
    ? Math.ceil(cardValue(tier, plus) * 0.11) // 안전 구간: 가치 비율
    : Math.ceil(BASE_VALUE[tier] * 0.12); // 도박·트로피 구간: 기본가 고정
}

/**
 * 보호료 = ceil(카드 가치 × 파괴율 × 1.35).
 *
 * 1.05였을 때는 기대 파괴손실보다 5%만 비싸 사실상 공짜 보험이었다. 그러면 도박
 * 구간(+6~+10)이 다시 무위험 이득 구간이 되어 위험 없는 노동 루프가 되살아난다.
 * 1.35로 올리면 보호권을 켜는 순간 기대손익이 음수로 꺾여, "이 한 장은
 * 지키겠다"는 대가를 실제로 치르는 선택이 된다.
 */
export function guardFee(tier: TierKey, plus: number): number {
  return Math.ceil(cardValue(tier, plus) * (oddsAt(plus, false).destroy / 100) * 1.35);
}

/**
 * 파산. 제일 싼 팩도 못 사고 보관함도 비었을 때다.
 * 보관함에 카드가 남아 있으면 팔아서 계속할 수 있으니 아직 끝이 아니다.
 */
export function isBankrupt(credits: number, vaultSize: number): boolean {
  return credits < cheapestPackPrice() && vaultSize === 0;
}
